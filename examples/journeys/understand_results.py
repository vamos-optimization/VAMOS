from __future__ import annotations

import argparse
import json
from pathlib import Path


def solve():
    from vamos import optimize

    return optimize(
        "zdt1",
        algorithm="nsgaii",
        pop_size=40,
        max_evaluations=400,
        engine="numpy",
        seed=42,
    )


def summarize(result) -> dict[str, object]:
    if result.X is None or result.F is None:
        raise RuntimeError("The example expects both decision and objective arrays.")
    front_F, front_indices = result.front(return_indices=True)
    return {
        "X_shape": list(result.X.shape),
        "F_shape": list(result.F.shape),
        "front_shape": list(front_F.shape),
        "evaluations": int(result.data["evaluations"]),
        "first_decision": result.X[0].tolist(),
        "first_objectives": result.F[0].tolist(),
        "front_indices": front_indices.tolist(),
    }


def write_svg(result, output: Path) -> None:
    if output.suffix.lower() != ".svg":
        raise ValueError("The maintained documentation figure must be an .svg file.")
    if output.exists():
        raise FileExistsError(f"Refusing to overwrite existing figure: {output}")
    if result.F is None:
        raise RuntimeError("The example expects objective values.")
    front_F = result.front()
    if front_F is None:
        raise RuntimeError("The example expects at least one solution.")

    width, height = 720, 500
    left, right, top, bottom = 72, 28, 48, 104
    plot_w = width - left - right
    plot_h = height - top - bottom
    f1 = result.F[:, 0]
    f2 = result.F[:, 1]
    x_min, x_max = float(f1.min()), float(f1.max())
    y_min, y_max = float(f2.min()), float(f2.max())
    x_pad = max((x_max - x_min) * 0.06, 1e-9)
    y_pad = max((y_max - y_min) * 0.06, 1e-9)
    x_min, x_max = x_min - x_pad, x_max + x_pad
    y_min, y_max = y_min - y_pad, y_max + y_pad

    def sx(value: float) -> float:
        return left + (value - x_min) / (x_max - x_min) * plot_w

    def sy(value: float) -> float:
        return top + (y_max - value) / (y_max - y_min) * plot_h

    lines = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="720" height="500" viewBox="0 0 720 500" role="img" aria-labelledby="title desc">',
        '<title id="title">Reading a VAMOS result: NSGA-II on ZDT1</title>',
        '<desc id="desc">Generated by examples/journeys/understand_results.py from a 40-member final population after 400 evaluations with seed 42 and the NumPy backend. Teal crosses mark the non-dominated subset returned by OptimizationResult.front(). This short run illustrates result structure, not convergence quality.</desc>',
        '<rect width="720" height="500" fill="#ffffff"/>',
        '<g font-family="Arial, Helvetica, sans-serif" fill="#0B2545">',
        '<text x="360" y="28" text-anchor="middle" font-size="18" font-weight="600">Reading a VAMOS result: NSGA-II on ZDT1</text>',
        f'<line x1="{left}" y1="{top + plot_h}" x2="{left + plot_w}" y2="{top + plot_h}" stroke="#374151"/>',
        f'<line x1="{left}" y1="{top}" x2="{left}" y2="{top + plot_h}" stroke="#374151"/>',
    ]
    for step in range(6):
        value = x_min + (x_max - x_min) * step / 5
        x = sx(value)
        lines.append(
            f'<line x1="{x:.2f}" y1="{top + plot_h}" x2="{x:.2f}" y2="{top + plot_h + 5}" stroke="#374151"/>'
        )
        lines.append(
            f'<text x="{x:.2f}" y="{top + plot_h + 22}" text-anchor="middle" font-size="11">{value:.2f}</text>'
        )
    for step in range(6):
        value = y_min + (y_max - y_min) * step / 5
        y = sy(value)
        lines.append(f'<line x1="{left - 5}" y1="{y:.2f}" x2="{left}" y2="{y:.2f}" stroke="#374151"/>')
        lines.append(f'<text x="{left - 10}" y="{y + 4:.2f}" text-anchor="end" font-size="11">{value:.2f}</text>')
    lines.extend(
        [
            f'<text x="{left + plot_w / 2:.2f}" y="452" text-anchor="middle" font-size="13">Objective 1 (minimize)</text>',
            f'<text x="18" y="{top + plot_h / 2:.2f}" text-anchor="middle" font-size="13" transform="rotate(-90 18 {top + plot_h / 2:.2f})">Objective 2 (minimize)</text>',
            "</g>",
            '<g fill="#94A3B8" fill-opacity="0.82" stroke="#64748B" stroke-width="0.7">',
        ]
    )
    for row in result.F:
        lines.append(f'<circle cx="{sx(float(row[0])):.2f}" cy="{sy(float(row[1])):.2f}" r="4"/>')
    lines.append("</g>")
    lines.append('<g stroke="#14B8A6" stroke-width="2.2" stroke-linecap="round">')
    for row in front_F:
        x, y = sx(float(row[0])), sy(float(row[1]))
        lines.append(
            f'<path d="M {x - 5:.2f} {y - 5:.2f} L {x + 5:.2f} {y + 5:.2f} M {x - 5:.2f} {y + 5:.2f} L {x + 5:.2f} {y - 5:.2f}"/>'
        )
    lines.extend(
        [
            "</g>",
            '<g font-family="Arial, Helvetica, sans-serif" font-size="12" fill="#0B2545">',
            '<circle cx="484" cy="62" r="4" fill="#94A3B8" stroke="#64748B"/><text x="496" y="66">Returned population</text>',
            '<path d="M 479 80 L 489 90 M 479 90 L 489 80" stroke="#14B8A6" stroke-width="2.2"/><text x="496" y="89">Non-dominated subset</text>',
            '<text x="360" y="486" text-anchor="middle" font-size="11" fill="#374151">40 returned solutions · 400 evaluations · seed 42 · NumPy · illustrative, not a convergence claim</text>',
            "</g>",
            "</svg>",
        ]
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Inspect the arrays returned by a small VAMOS optimization.")
    parser.add_argument("--plot", type=Path, help="Optional .svg path for the explanatory figure.")
    args = parser.parse_args()
    result = solve()
    report = summarize(result)
    if args.plot is not None:
        write_svg(result, args.plot)
        report["figure"] = str(args.plot)
    else:
        report["figure"] = None
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
