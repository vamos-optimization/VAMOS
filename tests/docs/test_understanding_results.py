def _python_blocks(path: Path) -> list[str]:
    return re.findall(r"```python\n(.*?)\n```", path.read_text(encoding="utf-8"), re.DOTALL)


def test_quickstart_first_run_and_front_are_executable_and_aligned() -> None:
    namespace: dict = {}
    blocks = _python_blocks(QUICKSTART)
    exec(compile(blocks[0], str(QUICKSTART), "exec"), namespace)
    exec(compile(blocks[1], str(QUICKSTART), "exec"), namespace)
    result = namespace["result"]
    front_F = namespace["front_F"]
    front_indices = namespace["front_indices"]
    front_X = namespace["front_X"]

    assert result.X is not None and result.F is not None
    assert result.X.shape == (40, 30)
    assert result.F.shape == (40, 2)
    assert result.data["evaluations"] == 400
    assert len(front_F) == len(front_X) == len(front_indices)
    np.testing.assert_array_equal(result.F[front_indices], front_F)
    np.testing.assert_array_equal(result.X[front_indices], front_X)

    recomputed = np.empty_like(result.F)
    ZDT1(n_var=30).evaluate(result.X, {"F": recomputed})
    np.testing.assert_allclose(result.F, recomputed)

    resolved = result.explain_defaults()["resolved_spec"]
    assert resolved["algorithm"]["config"]["result_mode"] == "population"
    np.testing.assert_array_equal(result.data["population"]["X"], result.X)
    np.testing.assert_array_equal(result.data["population"]["F"], result.F)


def test_explicit_nsgaii_config_keeps_configuration_result_mode() -> None:
    config = NSGAIIConfig.default(pop_size=40, n_var=30)
    result = optimize(
        ZDT1(n_var=30),
        algorithm="nsgaii",
        algorithm_config=config,
        max_evaluations=400,
        engine="numpy",
        seed=42,
    )
    assert result.F is not None
    resolved = result.explain_defaults()["resolved_spec"]
    assert resolved["algorithm"]["config"]["result_mode"] == "non_dominated"
    assert len(result.F) <= 40
    assert result.data["population"]["F"].shape == (40, 2)


def test_understanding_results_example_matches_quickstart_and_writes_nothing_by_default(tmp_path: Path) -> None:
    example = runpy.run_path(str(EXAMPLE))
    result = example["solve"]()
    report = example["summarize"](result)
    assert report["X_shape"] == [40, 30]
    assert report["F_shape"] == [40, 2]
    assert report["evaluations"] == 400

    completed = subprocess.run(
        [sys.executable, str(EXAMPLE)],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        check=True,
    )
    cli_report = json.loads(completed.stdout)
    assert cli_report["X_shape"] == [40, 30]
    assert cli_report["F_shape"] == [40, 2]
    assert cli_report["figure"] is None
    assert list(tmp_path.iterdir()) == []


def test_maintained_svg_has_provenance_and_generator_can_reproduce_structure(tmp_path: Path) -> None:
    tree = ElementTree.parse(FIGURE)
    root = tree.getroot()
    assert root.tag == "{http://www.w3.org/2000/svg}svg"
    text = FIGURE.read_text(encoding="utf-8")
    assert "Generated by examples/journeys/understand_results.py" in text
    assert "400 evaluations" in text
    assert "not convergence quality" in text
    assert "<script" not in text

    example = runpy.run_path(str(EXAMPLE))
    output = tmp_path / "result.svg"
    example["write_svg"](example["solve"](), output)
    generated = output.read_text(encoding="utf-8")
    assert "Returned population" in generated
    assert "Non-dominated subset" in generated
    with pytest.raises(FileExistsError):
        example["write_svg"](example["solve"](), output)
    with pytest.raises(ValueError, match=".svg"):
        example["write_svg"](example["solve"](), tmp_path / "result.png")


def test_result_learning_path_is_discoverable_and_cross_linked() -> None:
    config = yaml.safe_load((ROOT / "mkdocs.yml").read_text(encoding="utf-8"))
    nav = yaml.safe_dump(config["nav"], sort_keys=False)
    assert "guide/understanding-results.md" in nav

    guide = GUIDE.read_text(encoding="utf-8")
    quickstart = QUICKSTART.read_text(encoding="utf-8")
    api = (ROOT / "docs" / "reference" / "api" / "results.md").read_text(encoding="utf-8")
    assert "result.front(return_indices=True)" in guide
    assert "result.explain_defaults()" in guide
    assert "Understanding optimization results" in quickstart
    assert "understanding-results.md" in api
